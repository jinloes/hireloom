export function normalizeKeyword(term: string): string {
  return term.trim().replace(/\s+/g, " ").toLowerCase();
}

export function containsPhrase(text: string, phrase: string): boolean {
  const trimmed = phrase.trim();
  if (!trimmed) return false;
  const escaped = trimmed
    .replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
    .replace(/\s+/g, "\\s+");
  return new RegExp(`(^|[^a-z0-9])${escaped}($|[^a-z0-9])`, "i").test(text);
}

function resumeSearchableText(resume: Resume): string {
  return [
    resume.basics.headline,
    resume.summary,
    ...resume.skills,
    ...resume.skillGroups.flatMap((group) => [group.category, ...group.items]),
    ...resume.experience.flatMap((entry) => [entry.role, ...entry.bullets]),
    ...resume.projects.flatMap((project) => [
      project.name,
      project.subtitle,
      ...project.bullets,
    ]),
    ...resume.education.map((entry) => entry.degree),
    ...resume.certifications.flatMap((cert) => [cert.name, cert.issuer]),
    ...resume.customSections.flatMap((section) => [
      section.title,
      ...section.entries.flatMap((entry) => [
        entry.heading,
        entry.subheading,
        ...entry.bullets,
      ]),
    ]),
  ].join(" ");
}

function isUsefulDynamicToken(raw: string): boolean {
  const cleaned = raw.trim().replace(/^[([{'"`]+|[)\]}'"`.,;:!?]+$/g, "");
  if (cleaned.length < 2 || cleaned.length > 40) return false;
  const lower = cleaned.toLowerCase();
  if (STOPWORDS.has(lower)) return false;
  if (/^\d+([.,-]\d+)*\+?$/.test(cleaned)) return false;
  if (/^https?:\/\//i.test(cleaned) || cleaned.includes("@")) return false;
  return /[a-z]/i.test(cleaned);
}

function extractDynamicCandidates(jobDescription: string): string[] {
  const found: string[] = [];

  // 1. CamelCase, acronyms, dotted/slashed/plus technical tokens (e.g. FastAPI, GraphQL, Vue.js, CI/CD, C++, OAuth2)
  const techPattern =
    /(?:^|[\s([,/])([A-Z][a-z0-9]+[A-Z][A-Za-z0-9.+#/-]*|[A-Z]{2,8}(?:[0-9]+|\/[A-Z]{2,8})?|[A-Za-z][A-Za-z0-9]*(?:\.js|\.ts|\.py|\.io|\.net|\+\+|#))/g;
  for (const match of jobDescription.matchAll(techPattern)) {
    const token = match[1]?.trim();
    if (token && isUsefulDynamicToken(token)) {
      found.push(token.toLowerCase());
    }
  }

  // 2. Comma/slash/and-separated lists after cue phrases ("experience with X, Y, and Z")
  const cuePattern =
    /\b(?:experience\s+(?:with|in)|proficiency\s+(?:with|in)|proficient\s+(?:with|in)|familiarity\s+with|knowledge\s+of|expertise\s+in|hands-on\s+with|stack\s*:\s*|skills\s*:\s*|technologies\s*:\s*)([^\n.;!?]{3,140})/gi;
  for (const match of jobDescription.matchAll(cuePattern)) {
    const clause = match[1] ?? "";
    const parts = clause
      .split(/,|\/|\band\b|\bor\b|\bsuch as\b|\bincluding\b/i)
      .map((item) =>
        item
          .trim()
          .replace(/^(?:a|an|the|modern|strong|deep|solid)\s+/i, "")
          .replace(/\s+\b(?:preferred|required|a plus|is a plus|etc)\b.*$/i, "")
          .trim(),
      );
    for (const part of parts) {
      const words = part.split(/\s+/).filter(Boolean);
      if (
        words.length >= 1 &&
        words.length <= 3 &&
        isUsefulDynamicToken(part)
      ) {
        if (words.every((word) => !STOPWORDS.has(word.toLowerCase()))) {
          found.push(part.toLowerCase());
        }
      }
    }
  }

  return found;
}

export function extractJobKeywords(resume: Resume): JobKeyword[] {
  if (!resume.jobDescription.trim()) return [];
  const content = resumeSearchableText(resume);
  const skippedSet = new Set(
    (resume.skippedKeywords ?? []).map(normalizeKeyword),
  );
  const seen = new Set<string>();
  const results: JobKeyword[] = [];

  const pushTerm = (term: string) => {
    const normalized = normalizeKeyword(term);
    if (!normalized || seen.has(normalized)) return;
    if (!containsPhrase(resume.jobDescription, normalized)) return;
    seen.add(normalized);
    results.push({
      term: normalized,
      matched: containsPhrase(content, normalized),
      skipped: skippedSet.has(normalized),
    });
  };

  for (const term of CURATED_VOCABULARY) {
    pushTerm(term);
  }
  for (const dynamicTerm of extractDynamicCandidates(resume.jobDescription)) {
    if (results.length >= 40) break;
    pushTerm(dynamicTerm);
  }

  return results;
}
